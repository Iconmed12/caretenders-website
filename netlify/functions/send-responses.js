const { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle } = require('docx');

exports.handler = async (event) => {
  const cors = {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Access-Control-Allow-Methods': 'POST, OPTIONS'
  };
  if (event.httpMethod === 'OPTIONS') return { statusCode: 200, headers: cors, body: '' };

  try {
    const { responses, clientEmail, clientName, tenderTitle, sessionId,
            sqDocBase64, sqFileName, sqData, includeSq, tenderId } = JSON.parse(event.body);
    const RESEND_KEY = process.env.RESEND_API_KEY;
    const FROM_EMAIL = process.env.RESEND_FROM_EMAIL || 'noreply@icongrp.co.uk';
    const ICONGRP_EMAIL = 'consulting@icongrp.co.uk';

    if (!RESEND_KEY) return { statusCode: 500, headers: cors, body: JSON.stringify({ error: 'RESEND_API_KEY not set' }) };

    // ── Fetch completion pack server-side (never travels through the client) ──
    var completionDocs = [];
    var submissionPortal = null;
    var tenderDeadline = '';
    if (tenderId) {
      try {
        var sbKey = process.env.SUPABASE_ANON_KEY;
        var packRes = await fetch(
          'https://igpjfpncfuawikoyzfcd.supabase.co/rest/v1/tenders?id=eq.' + encodeURIComponent(tenderId) +
          '&select=deadline,completion_docs,submission_portal',
          { headers: { apikey: sbKey, Authorization: 'Bearer ' + sbKey } }
        );
        var packRows = await packRes.json();
        if (Array.isArray(packRows) && packRows[0]) {
          completionDocs = packRows[0].completion_docs || [];
          submissionPortal = packRows[0].submission_portal || null;
          tenderDeadline = packRows[0].deadline || '';
        }
      } catch (e) { console.log('Completion pack fetch failed (non-fatal):', e.message); }
    }

    // ── Build tender responses Word doc (existing) ──
    var children = [];
    children.push(new Paragraph({
      children: [new TextRun({ text: 'CANA AI  |  ICONGRP CONSULTING', bold: true, size: 20, color: '00C9E0', font: 'Arial' })],
      alignment: AlignmentType.CENTER, spacing: { after: 100 }
    }));
    children.push(new Paragraph({
      border: { bottom: { style: BorderStyle.SINGLE, size: 4, color: '00C9E0' } }, spacing: { after: 300 }
    }));
    children.push(new Paragraph({
      children: [new TextRun({ text: tenderTitle || 'Tender Response Document', bold: true, size: 32, font: 'Arial' })],
      alignment: AlignmentType.CENTER, spacing: { after: 200 }
    }));
    children.push(new Paragraph({
      children: [new TextRun({ text: 'Organisation: ' + (clientName || 'Unknown'), size: 22, font: 'Arial' })],
      alignment: AlignmentType.CENTER, spacing: { after: 600 }
    }));

    (responses || []).forEach(function(r, i) {
      children.push(new Paragraph({
        children: [new TextRun({ text: 'Question ' + (i + 1), bold: true, size: 26, color: 'FFFFFF', font: 'Arial' })],
        spacing: { before: 400, after: 100 }, 
      }));
      children.push(new Paragraph({
        children: [new TextRun({ text: r.question || '', bold: true, size: 22, font: 'Arial', color: '0B1929' })],
        spacing: { after: 160 }, border: { bottom: { style: BorderStyle.SINGLE, size: 2, color: '00C9E0' } }
      }));
      (r.answer || '').split('\n').forEach(function(line) {
        if (line.trim()) {
          children.push(new Paragraph({
            children: [new TextRun({ text: line, size: 22, font: 'Arial' })], spacing: { after: 120 }
          }));
        }
      });
    });

    children.push(new Paragraph({
      border: { top: { style: BorderStyle.SINGLE, size: 2, color: 'CCCCCC' } }, spacing: { before: 600, after: 100 }
    }));
    children.push(new Paragraph({
      children: [new TextRun({ text: 'Generated by Cana AI  |  ICONGRP Consulting  |  consulting@icongrp.co.uk', size: 18, color: '999999', font: 'Arial' })],
      alignment: AlignmentType.CENTER
    }));

    var doc = new Document({ sections: [{ properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 } } }, children: children }] });
    var safeClientName = (clientName || 'Client').replace(/\s+/g, '_');
    try {
      var docBuffer = await Packer.toBuffer(doc);
      docBase64 = docBuffer.toString('base64');
    } catch(docErr) {
      console.error('Word doc generation failed:', docErr.message);
      // Continue — email will send without Word attachment
    }

    // ── Build completion report HTML section ──
    var reportHtml = '';
    if (includeSq && sqData) {
      var autoFields = [], aiFields = [], confirmFields = [], missingFields = [];
      (sqData.sections || []).forEach(function(s) {
        (s.fields || []).forEach(function(f) {
          if (f.field_type === 'auto_fill') autoFields.push(f.question);
          else if (f.field_type === 'ai_draft') aiFields.push(f.question);
          else if (f.field_type === 'client_confirm') confirmFields.push(f.question);
        });
      });

      reportHtml = '<div style="background:#f8fafc;border:1px solid #e2e8f0;border-radius:10px;padding:24px;margin-top:32px;">' +
        '<h2 style="color:#0B1929;font-size:18px;margin:0 0 6px;">📋 Selection Questionnaire — Completion Report</h2>' +
        '<p style="color:#6b7280;font-size:13px;margin:0 0 20px;">Your completed SQ document is attached. Review before submitting.</p>';

      if (autoFields.length) {
        reportHtml += '<div style="margin-bottom:16px;">' +
          '<div style="font-size:13px;font-weight:700;color:#166534;margin-bottom:8px;">✅ Auto-filled (' + autoFields.length + ' fields)</div>' +
          '<div style="background:#f0fdf4;border-radius:6px;padding:12px;font-size:12px;color:#166534;line-height:1.8;">' +
          autoFields.slice(0,8).join(' · ') + (autoFields.length > 8 ? ' · and ' + (autoFields.length-8) + ' more...' : '') +
          '</div></div>';
      }
      if (aiFields.length) {
        reportHtml += '<div style="margin-bottom:16px;">' +
          '<div style="font-size:13px;font-weight:700;color:#5b21b6;margin-bottom:8px;">🤖 AI drafted (' + aiFields.length + ' sections)</div>' +
          '<div style="background:rgba(124,58,237,0.06);border-radius:6px;padding:12px;font-size:12px;color:#5b21b6;line-height:1.8;">' +
          aiFields.slice(0,6).join(' · ') + (aiFields.length > 6 ? ' · and ' + (aiFields.length-6) + ' more...' : '') +
          '</div></div>';
      }
      if (confirmFields.length) {
        reportHtml += '<div style="margin-bottom:16px;">' +
          '<div style="font-size:13px;font-weight:700;color:#92400e;margin-bottom:8px;">⚠️ Requires your personal signature</div>' +
          '<div style="background:#fffbeb;border-radius:6px;padding:12px;">' +
          confirmFields.map(function(q){ return '<div style="font-size:12px;color:#78350f;padding:3px 0;border-bottom:1px solid #fde68a;">☐ ' + q + '</div>'; }).join('') +
          '</div></div>';
      }

      reportHtml += '<div style="background:#fef2f2;border-radius:8px;padding:12px;margin-top:8px;">' +
        '<div style="font-size:13px;font-weight:700;color:#c53030;margin-bottom:4px;">🔴 Action required before submission</div>' +
        '<div style="font-size:12px;color:#c53030;line-height:1.8;">' +
        '• Review all AI-drafted sections and confirm accuracy<br>' +
        '• Tick and sign all declaration sections highlighted above<br>' +
        '• Ensure all insurance certificates and policies are attached<br>' +
        '• Do not submit unsigned or incomplete documents</div>' +
        '</div></div>';
    }

    // ── Build email HTML ──
    var htmlBody = '<div style="font-family:Arial,sans-serif;max-width:640px;margin:0 auto;">' +
      '<div style="background:#0B1929;padding:24px;border-radius:8px 8px 0 0;">' +
        '<h1 style="color:#00C9E0;margin:0;font-size:22px;">Cana AI</h1>' +
        '<p style="color:rgba(255,255,255,0.6);margin:4px 0 0;font-size:13px;">ICONGRP Consulting</p>' +
      '</div>' +
      '<div style="background:#ffffff;padding:28px;border:1px solid #e2e8f0;border-top:none;border-radius:0 0 8px 8px;">' +
        '<h2 style="color:#0B1929;font-size:20px;margin:0 0 8px;">Your ' + (includeSq ? 'SQ &amp; ' : '') + 'Tender Responses</h2>' +
        '<p style="color:#6b7280;margin:0 0 4px;"><strong>Tender:</strong> ' + (tenderTitle || '') + '</p>' +
        '<p style="color:#6b7280;margin:0 0 20px;"><strong>Organisation:</strong> ' + (clientName || '') + '</p>';

    // Attached files list
    var attachedFiles = ['<strong>Cana_AI_Tender_Responses.docx</strong> — ' + (responses ? responses.length : 0) + ' complete bid responses'];
    if (includeSq && sqDocBase64) attachedFiles.push('<strong>' + (sqFileName || 'Selection_Questionnaire_Completed.docx') + '</strong> — completed SQ document (original template filled in)');
    (completionDocs || []).forEach(function(d) {
      attachedFiles.push('<strong>' + (d.fileName || d.label || 'Document') + '</strong> — for your completion: ' + (d.label || ''));
    });

    htmlBody += '<div style="background:#f0fdf4;border:1px solid #bbf7d0;border-radius:8px;padding:14px 16px;margin-bottom:24px;">' +
      '<div style="font-size:13px;font-weight:700;color:#166534;margin-bottom:8px;">📎 ' + attachedFiles.length + ' document' + (attachedFiles.length>1?'s':'') + ' attached</div>' +
      attachedFiles.map(function(f){ return '<div style="font-size:12px;color:#166534;padding:2px 0;">✓ ' + f + '</div>'; }).join('') +
      '</div>';

    htmlBody += '<hr style="border:1px solid #e5e7eb;margin-bottom:24px;">';

    // Responses preview
    (responses || []).forEach(function(r, i) {
      htmlBody += '<div style="margin-bottom:28px;">' +
        '<h3 style="color:#0B1929;border-left:4px solid #00C9E0;padding-left:12px;font-size:15px;">Q' + (i+1) + ': ' + (r.question || '').substring(0, 120) + (r.question && r.question.length > 120 ? '...' : '') + '</h3>' +
        '<p style="color:#374151;line-height:1.8;font-size:14px;">' + (r.answer || '').substring(0, 500).replace(/\n/g, '<br>') + (r.answer && r.answer.length > 500 ? '...' : '') + '</p>' +
        '</div>';
    });

    // ── DELIVERY CHECKLIST ──
    var checklistHtml = '<div style="border:2px solid #0B1929;border-radius:10px;overflow:hidden;margin:28px 0;">' +
      '<div style="background:#0B1929;padding:14px 18px;"><span style="color:#00C9E0;font-weight:800;font-size:15px;letter-spacing:0.04em;">YOUR SUBMISSION CHECKLIST</span></div>' +
      '<div style="padding:18px;">';

    checklistHtml += '<div style="font-size:13px;font-weight:800;color:#0B1929;margin-bottom:8px;">1. Completed by Cana AI (review required)</div>';
    checklistHtml += '<div style="background:#fef2f2;border:1.5px solid #fca5a5;border-radius:8px;padding:12px 14px;margin-bottom:18px;">';
    if (includeSq && sqDocBase64) {
      checklistHtml += '<div style="font-size:13px;color:#0B1929;padding:4px 0;">☑ Selection Questionnaire — completed</div>';
    }
    checklistHtml += '<div style="font-size:13px;color:#0B1929;padding:4px 0;">☑ ' + (responses ? responses.length : 0) + ' tender responses, written by Cana AI for your review</div>';
    checklistHtml += '<div style="font-size:13px;font-weight:800;color:#c53030;margin-top:8px;">🔴 YOU MUST READ THROUGH EVERY DOCUMENT BEFORE SUBMISSION. Check all answers reflect your business accurately.</div>';
    checklistHtml += '</div>';

    if (completionDocs && completionDocs.length) {
      checklistHtml += '<div style="font-size:13px;font-weight:800;color:#0B1929;margin-bottom:8px;">2. Attached for YOUR completion</div>';
      checklistHtml += '<div style="background:#fffbeb;border:1.5px solid #fde68a;border-radius:8px;padding:12px 14px;margin-bottom:18px;">';
      completionDocs.forEach(function(d) {
        checklistHtml += '<div style="font-size:13px;color:#78350f;padding:4px 0;">☐ ' + (d.label || d.fileName || 'Document') + ' — complete, sign and include with your submission</div>';
      });
      checklistHtml += '</div>';
    }

    var stepNum = (completionDocs && completionDocs.length) ? '3' : '2';
    checklistHtml += '<div style="font-size:13px;font-weight:800;color:#0B1929;margin-bottom:8px;">' + stepNum + '. Where to submit</div>';
    checklistHtml += '<div style="background:#f0fdf4;border:1.5px solid #bbf7d0;border-radius:8px;padding:12px 14px;">';
    if (submissionPortal && submissionPortal.name) {
      checklistHtml += '<div style="font-size:13px;color:#166534;padding:2px 0;">Portal: <strong>' + submissionPortal.name + '</strong></div>';
      if (submissionPortal.url) {
        checklistHtml += '<div style="padding:8px 0 4px;"><a href="' + submissionPortal.url + '" style="display:inline-block;background:#166534;color:#ffffff;font-size:13px;font-weight:700;padding:9px 18px;border-radius:7px;text-decoration:none;">Go to submission portal →</a></div>';
      }
    } else {
      checklistHtml += '<div style="font-size:13px;color:#166534;padding:2px 0;">Submit via the buyer portal stated in the tender documents.</div>';
    }
    if (tenderDeadline) {
      checklistHtml += '<div style="font-size:13px;font-weight:700;color:#c53030;padding:6px 0 0;">⏰ Submission deadline: ' + tenderDeadline + ' — do not leave it to the last day.</div>';
    }
    checklistHtml += '</div></div></div>';

    htmlBody += checklistHtml;
    htmlBody += reportHtml;

    htmlBody += '<hr style="margin-top:32px;"><p style="color:#9ca3af;font-size:11px;text-align:center;">Generated by Cana AI | ICONGRP Consulting | consulting@icongrp.co.uk</p>' +
      '</div></div>';

    // ── Build attachments array ──
    var attachments = [];
    if (docBase64) {
      attachments.push({ filename: 'Cana_AI_Tender_Responses.docx', content: docBase64 });
    }
    if (includeSq && sqDocBase64) {
      attachments.push({
        filename: sqFileName || 'Selection_Questionnaire_Completed.docx',
        content: sqDocBase64
      });
    }
    // Completion documents — guard total size against email provider limits (~40MB)
    var totalAttachBytes = attachments.reduce(function(sum, a) { return sum + Math.ceil((a.content || '').length * 0.75); }, 0);
    var skippedDocs = [];
    (completionDocs || []).forEach(function(d) {
      var bytes = Math.ceil((d.data || '').length * 0.75);
      if (totalAttachBytes + bytes > 35 * 1024 * 1024) { skippedDocs.push(d.fileName || d.label); return; }
      attachments.push({ filename: d.fileName || ((d.label || 'document') + '.pdf'), content: d.data });
      totalAttachBytes += bytes;
    });
    if (skippedDocs.length) console.log('Skipped attachments over size limit:', skippedDocs.join(', '));

    var errors = [];

    // ── Send to client ──
    if (clientEmail) {
      var clientRes = await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: { 'Authorization': 'Bearer ' + RESEND_KEY, 'Content-Type': 'application/json' },
        body: JSON.stringify({
          from: 'Cana AI <' + FROM_EMAIL + '>',
          to: clientEmail,
          subject: (includeSq ? '📋 Your SQ & Tender Responses — ' : '✅ Your Tender Responses — ') + (tenderTitle || '').substring(0, 50),
          html: htmlBody,
          attachments: attachments
        })
      });
      if (!clientRes.ok) errors.push('Client email: ' + JSON.stringify(await clientRes.json()));
      else console.log('Client email sent to:', clientEmail);
    }

    // ── Send to ICONGRP ──
    var iconHtml = htmlBody.replace(
      '<h2 style="color:#0B1929;font-size:20px;margin:0 0 8px;">',
      '<h2 style="color:#0B1929;font-size:20px;margin:0 0 8px;">New Sale — '
    ).replace(
      '<p style="color:#6b7280;margin:0 0 4px;"><strong>Tender:</strong>',
      '<div style="background:#e8f7ee;padding:10px 14px;border-radius:6px;margin-bottom:12px;font-size:13px;"><strong>Client:</strong> ' + (clientName||'') + ' | <strong>Email:</strong> ' + (clientEmail||'N/A') + ' | <strong>Ref:</strong> ' + (sessionId||'') + '</div><p style="color:#6b7280;margin:0 0 4px;"><strong>Tender:</strong>'
    );

    var iconRes = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: { 'Authorization': 'Bearer ' + RESEND_KEY, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        from: 'Cana AI <' + FROM_EMAIL + '>',
        to: ICONGRP_EMAIL,
        subject: 'New Sale — ' + (clientName||'') + ' | ' + (tenderTitle||'').substring(0,40),
        html: iconHtml,
        attachments: attachments
      })
    });
    if (!iconRes.ok) errors.push('ICONGRP email: ' + JSON.stringify(await iconRes.json()));
    else console.log('ICONGRP email sent');

    if (errors.length) return { statusCode: 500, headers: cors, body: JSON.stringify({ error: errors.join(', ') }) };
    return { statusCode: 200, headers: cors, body: JSON.stringify({ sent: true }) };

  } catch(err) {
    console.log('send-responses error:', err.message);
    return { statusCode: 500, headers: cors, body: JSON.stringify({ error: err.message }) };
  }
};
