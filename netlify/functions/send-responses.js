const { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle } = require('docx');

exports.handler = async (event) => {
  const cors = {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Access-Control-Allow-Methods': 'POST, OPTIONS'
  };
  if (event.httpMethod === 'OPTIONS') return { statusCode: 200, headers: cors, body: '' };

  try {
    const { responses, clientEmail, clientName, tenderTitle, sessionId } = JSON.parse(event.body);
    const RESEND_KEY = process.env.RESEND_API_KEY;
    const ICONGRP_EMAIL = 'consulting@icongrp.co.uk';

    // Build Word document
    const children = [];

    // Title
    children.push(new Paragraph({
      text: 'Cana AI — Tender Response Document',
      heading: HeadingLevel.TITLE,
      alignment: AlignmentType.CENTER,
      spacing: { after: 200 }
    }));

    children.push(new Paragraph({
      text: 'Tender: ' + tenderTitle,
      heading: HeadingLevel.HEADING_2,
      alignment: AlignmentType.CENTER,
      spacing: { after: 100 }
    }));

    children.push(new Paragraph({
      text: 'Organisation: ' + clientName,
      alignment: AlignmentType.CENTER,
      spacing: { after: 400 }
    }));

    children.push(new Paragraph({
      text: 'Generated by Cana AI | ICONGRP Consulting | consulting@icongrp.co.uk',
      alignment: AlignmentType.CENTER,
      spacing: { after: 600 }
    }));

    // Each question and answer
    responses.forEach(function(r, i) {
      children.push(new Paragraph({
        text: 'Question ' + (i + 1) + ': ' + r.question,
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 400, after: 200 },
        border: { bottom: { style: BorderStyle.SINGLE, size: 1, color: '00C9E0' } }
      }));

      var answerLines = (r.answer || '').split('\n');
      answerLines.forEach(function(line) {
        if (line.trim()) {
          children.push(new Paragraph({
            children: [new TextRun({ text: line, size: 24 })],
            spacing: { after: 120 }
          }));
        }
      });
    });

    const doc = new Document({
      sections: [{ children: children }]
    });

    const docBuffer = await Packer.toBuffer(doc);
    const docBase64 = docBuffer.toString('base64');

    // Build HTML email body
    var htmlBody = '<div style="font-family: Arial, sans-serif; max-width: 800px; margin: 0 auto;">';
    htmlBody += '<div style="background: #0B1929; padding: 24px; border-radius: 8px 8px 0 0;">';
    htmlBody += '<h1 style="color: #00C9E0; margin: 0; font-size: 24px;">Cana AI</h1>';
    htmlBody += '<p style="color: rgba(255,255,255,0.7); margin: 4px 0 0;">ICONGRP Consulting</p></div>';
    htmlBody += '<div style="background: #f9fafb; padding: 24px; border-radius: 0 0 8px 8px;">';
    htmlBody += '<h2 style="color: #0B1929;">Your Full Tender Responses</h2>';
    htmlBody += '<p style="color: #6b7280;"><strong>Tender:</strong> ' + tenderTitle + '</p>';
    htmlBody += '<p style="color: #6b7280;"><strong>Organisation:</strong> ' + clientName + '</p>';
    htmlBody += '<p style="color: #6b7280; margin-bottom: 24px;">Your Word document is attached. All ' + responses.length + ' responses are included in full.</p>';
    htmlBody += '<hr style="border: 1px solid #e5e7eb; margin-bottom: 24px;">';

    responses.forEach(function(r, i) {
      htmlBody += '<div style="margin-bottom: 32px;">';
      htmlBody += '<h3 style="color: #0B1929; border-bottom: 2px solid #00C9E0; padding-bottom: 8px;">Question ' + (i+1) + ': ' + r.question.substring(0, 120) + '</h3>';
      htmlBody += '<p style="color: #374151; line-height: 1.8;">' + (r.answer || '').replace(/\n/g, '<br>') + '</p>';
      htmlBody += '</div>';
    });

    htmlBody += '<hr style="border: 1px solid #e5e7eb;">';
    htmlBody += '<p style="color: #9ca3af; font-size: 12px; margin-top: 16px;">Generated by Cana AI | ICONGRP Consulting | consulting@icongrp.co.uk</p>';
    htmlBody += '</div></div>';

    // Send to client
    if (clientEmail) {
      await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: { 'Authorization': 'Bearer ' + RESEND_KEY, 'Content-Type': 'application/json' },
        body: JSON.stringify({
          from: 'Cana AI <cana@icongrp.co.uk>',
          to: clientEmail,
          subject: 'Your Cana AI Tender Responses — ' + tenderTitle.substring(0, 50),
          html: htmlBody,
          attachments: [{
            filename: 'Cana_AI_Tender_Responses.docx',
            content: docBase64
          }]
        })
      });
    }

    // Send to ICONGRP
    var icongrpBody = htmlBody.replace(
      '<h2 style="color: #0B1929;">Your Full Tender Responses</h2>',
      '<h2 style="color: #0B1929;">New Cana AI Purchase</h2><p style="background:#e8f7ee;padding:12px;border-radius:6px;color:#1a7a3f;"><strong>Client:</strong> ' + clientName + ' | <strong>Email:</strong> ' + (clientEmail||'not provided') + ' | <strong>Session:</strong> ' + sessionId + '</p>'
    );

    await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: { 'Authorization': 'Bearer ' + RESEND_KEY, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        from: 'Cana AI <cana@icongrp.co.uk>',
        to: ICONGRP_EMAIL,
        subject: 'New Cana AI Sale — ' + clientName + ' | ' + tenderTitle.substring(0, 40),
        html: icongrpBody,
        attachments: [{
          filename: 'Cana_AI_' + clientName.replace(/\s/g, '_') + '.docx',
          content: docBase64
        }]
      })
    });

    return { statusCode: 200, headers: cors, body: JSON.stringify({ sent: true }) };

  } catch(err) {
    return { statusCode: 500, headers: cors, body: JSON.stringify({ error: err.message }) };
  }
};
