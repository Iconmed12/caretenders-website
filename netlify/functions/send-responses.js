const { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle } = require('docx');

exports.handler = async (event) => {
  const cors = {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Access-Control-Allow-Methods': 'POST, OPTIONS'
  };
  if (event.httpMethod === 'OPTIONS') return { statusCode: 200, headers: cors, body: '' };

  try {
    const { responses, clientEmail, clientName, tenderTitle, sessionId } = JSON.parse(event.body);
    const RESEND_KEY = process.env.RESEND_API_KEY;
    const ICONGRP_EMAIL = 'consulting@icongrp.co.uk';

    if (!RESEND_KEY) {
      return { statusCode: 500, headers: cors, body: JSON.stringify({ error: 'RESEND_API_KEY not set' }) };
    }

    console.log('send-responses called for:', clientName, clientEmail, 'responses:', responses ? responses.length : 0);

    // Build Word document
    var children = [];

    // Header line
    children.push(new Paragraph({
      children: [new TextRun({ text: 'CANA AI  |  ICONGRP CONSULTING', bold: true, size: 20, color: '00C9E0', font: 'Arial' })],
      alignment: AlignmentType.CENTER,
      spacing: { after: 100 }
    }));

    children.push(new Paragraph({
      border: { bottom: { style: BorderStyle.SINGLE, size: 4, color: '00C9E0' } },
      spacing: { after: 300 }
    }));

    // Title
    children.push(new Paragraph({
      children: [new TextRun({ text: tenderTitle || 'Tender Response Document', bold: true, size: 32, font: 'Arial' })],
      alignment: AlignmentType.CENTER,
      spacing: { after: 200 }
    }));

    children.push(new Paragraph({
      children: [new TextRun({ text: 'Organisation: ' + (clientName || 'Unknown'), size: 22, font: 'Arial' })],
      alignment: AlignmentType.CENTER,
      spacing: { after: 600 }
    }));

    // Each Q&A
    (responses || []).forEach(function(r, i) {
      // Question heading
      children.push(new Paragraph({
        children: [new TextRun({ text: 'Question ' + (i + 1), bold: true, size: 26, color: 'FFFFFF', font: 'Arial', highlight: 'darkBlue' })],
        spacing: { before: 400, after: 100 },
        shading: { fill: '0B1929' }
      }));

      children.push(new Paragraph({
        children: [new TextRun({ text: r.question || '', bold: true, size: 22, font: 'Arial', color: '0B1929' })],
        spacing: { after: 160 },
        border: { bottom: { style: BorderStyle.SINGLE, size: 2, color: '00C9E0' } }
      }));

      // Answer paragraphs
      var answerLines = (r.answer || '').split('\n');
      answerLines.forEach(function(line) {
        if (line.trim()) {
          children.push(new Paragraph({
            children: [new TextRun({ text: line, size: 22, font: 'Arial' })],
            spacing: { after: 120 }
          }));
        }
      });
    });

    // Footer
    children.push(new Paragraph({
      border: { top: { style: BorderStyle.SINGLE, size: 2, color: 'CCCCCC' } },
      spacing: { before: 600, after: 100 }
    }));
    children.push(new Paragraph({
      children: [new TextRun({ text: 'Generated by Cana AI  |  ICONGRP Consulting  |  consulting@icongrp.co.uk', size: 18, color: '999999', font: 'Arial' })],
      alignment: AlignmentType.CENTER
    }));

    var doc = new Document({
      sections: [{
        properties: {
          page: {
            size: { width: 11906, height: 16838 },
            margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 }
          }
        },
        children: children
      }]
    });

    var docBuffer = await Packer.toBuffer(doc);
    var docBase64 = docBuffer.toString('base64');
    var safeClientName = (clientName || 'Client').replace(/\s+/g, '_');

    // Build HTML email
    var htmlBody = '<div style="font-family:Arial,sans-serif;max-width:800px;margin:0 auto;">';
    htmlBody += '<div style="background:#0B1929;padding:24px;border-radius:8px 8px 0 0;">';
    htmlBody += '<h1 style="color:#00C9E0;margin:0;font-size:24px;">Cana AI</h1>';
    htmlBody += '<p style="color:rgba(255,255,255,0.7);margin:4px 0 0;">ICONGRP Consulting</p></div>';
    htmlBody += '<div style="background:#f9fafb;padding:24px;border-radius:0 0 8px 8px;">';
    htmlBody += '<h2 style="color:#0B1929;">Your Full Tender Responses</h2>';
    htmlBody += '<p><strong>Tender:</strong> ' + (tenderTitle || '') + '</p>';
    htmlBody += '<p><strong>Organisation:</strong> ' + (clientName || '') + '</p>';
    htmlBody += '<p style="color:#6b7280;margin-bottom:24px;">All ' + (responses ? responses.length : 0) + ' responses are included below. Your Word document is attached.</p>';
    htmlBody += '<hr style="border:1px solid #e5e7eb;margin-bottom:24px;">';

    (responses || []).forEach(function(r, i) {
      htmlBody += '<div style="margin-bottom:32px;">';
      htmlBody += '<h3 style="color:#0B1929;border-left:4px solid #00C9E0;padding-left:12px;">Q' + (i+1) + ': ' + (r.question || '').substring(0, 150) + '</h3>';
      htmlBody += '<p style="color:#374151;line-height:1.8;">' + (r.answer || '').replace(/\n/g, '<br>') + '</p>';
      htmlBody += '</div>';
    });

    htmlBody += '<hr><p style="color:#9ca3af;font-size:12px;">Generated by Cana AI | ICONGRP Consulting | consulting@icongrp.co.uk</p></div></div>';

    var errors = [];

    // Send to client
    if (clientEmail) {
      var clientRes = await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: { 'Authorization': 'Bearer ' + RESEND_KEY, 'Content-Type': 'application/json' },
        body: JSON.stringify({
          from: 'Cana AI <cana@icongrp.co.uk>',
          to: clientEmail,
          subject: 'Your Cana AI Tender Responses — ' + (tenderTitle || '').substring(0, 50),
          html: htmlBody,
          attachments: [{ filename: 'Cana_AI_Tender_Responses.docx', content: docBase64 }]
        })
      });
      var clientData = await clientRes.json();
      if (!clientRes.ok) errors.push('Client email: ' + JSON.stringify(clientData));
      else console.log('Client email sent to:', clientEmail);
    }

    // Send to ICONGRP
    var iconHtml = htmlBody.replace(
      '<h2 style="color:#0B1929;">Your Full Tender Responses</h2>',
      '<h2 style="color:#0B1929;">New Cana AI Sale</h2>' +
      '<div style="background:#e8f7ee;padding:12px;border-radius:6px;margin-bottom:16px;">' +
      '<strong>Client:</strong> ' + (clientName||'') + ' | <strong>Email:</strong> ' + (clientEmail||'not provided') + ' | <strong>Ref:</strong> ' + (sessionId||'') + '</div>'
    );

    var iconRes = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: { 'Authorization': 'Bearer ' + RESEND_KEY, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        from: 'Cana AI <cana@icongrp.co.uk>',
        to: ICONGRP_EMAIL,
        subject: 'New Sale — ' + (clientName||'') + ' | ' + (tenderTitle||'').substring(0,40),
        html: iconHtml,
        attachments: [{ filename: 'Cana_AI_' + safeClientName + '.docx', content: docBase64 }]
      })
    });
    var iconData = await iconRes.json();
    if (!iconRes.ok) errors.push('ICONGRP email: ' + JSON.stringify(iconData));
    else console.log('ICONGRP email sent');

    if (errors.length) {
      console.log('Email errors:', errors);
      return { statusCode: 500, headers: cors, body: JSON.stringify({ error: errors.join(', ') }) };
    }

    return { statusCode: 200, headers: cors, body: JSON.stringify({ sent: true }) };

  } catch(err) {
    console.log('send-responses error:', err.message);
    return { statusCode: 500, headers: cors, body: JSON.stringify({ error: err.message }) };
  }
};
